export function formatReminderMessage(template: string, userName?: string | null): string {
  const name = (userName || '').trim() || 'друг';
  return template.replace(/\{name\}/g, name);
}

export function getReminderMessageByIndex(index: number): string {
  const safe = ((index % DAILY_REMINDER_MESSAGES.length) + DAILY_REMINDER_MESSAGES.length)
    % DAILY_REMINDER_MESSAGES.length;
  return DAILY_REMINDER_MESSAGES[safe];
}
